#!/usr/bin/env python3
"""xizhi.py sync 组件生成冒烟（离线）——模板输出契约 + 幂等 + 安全红线。

钉死：react/solid JSX 属性显式映射（只改名不改值、未知属性原样）、
vue/svelte 原样包裹、svg 复制带溯源头、生成器纯函数幂等、
harmonyos 拒绝、投毒 SVG 拒绝生成。
跑法：python3 -m pytest tests -q
"""
import io
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

os.environ.setdefault("XIZHI_CACHE", tempfile.mkdtemp(prefix="xizhi-cache-test-"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "scripts"))

import xizhi  # noqa: E402

SVG_FIXTURE = (b'<svg xmlns="http://www.w3.org/2000/svg" class="lucide" '
               b'stroke="currentColor" stroke-width="2">'
               b'<rect stroke-width="2" fill-rule="evenodd" fill="currentColor"/>'
               b'<rect data-foo="1"/></svg>')


def _sync_args(framework, out_dir, **kw):
    fields = dict(set="lucide", name="house", out=str(out_dir), framework=framework,
                  style=None, size=None, fill=None, variant=None, weight=None, wght=None,
                  version=None, format=None, color=None, sprite=False, refresh=False,
                  dir=None)
    fields.update(kw)
    return SimpleNamespace(**fields)


def _run_sync(framework, **kw):
    out_dir = Path(tempfile.mkdtemp(prefix="xizhi-sync-"))
    set_id = kw.pop("set", "lucide")
    name = kw.pop("name", "house")
    with mock.patch.object(xizhi, "http_get", return_value=SVG_FIXTURE), \
            mock.patch("sys.stdout", new_callable=io.StringIO) as out, \
            mock.patch("sys.stderr", new_callable=io.StringIO) as err:
        rc = xizhi.cmd_sync(_sync_args(framework, out_dir, set=set_id, name=name, **kw))
    return rc, out_dir, out.getvalue(), err.getvalue()


class TestSyncReact(unittest.TestCase):
    def test_component_contract(self):
        rc, out_dir, outv, errv = _run_sync("react")
        self.assertEqual(rc, 0)
        f = out_dir / "XizhiLucideHouse.tsx"
        self.assertTrue(f.is_file())
        text = f.read_text(encoding="utf-8")
        self.assertIn("// generated by xizhi (lucide:house)", text)  # 幂等标记
        self.assertIn("export function XizhiLucideHouse(props: SVGProps<SVGSVGElement>)", text)
        self.assertIn('className="lucide"', text)  # class → className（仅改名）
        self.assertEqual(text.count('strokeWidth="2"'), 2)  # 根标签 + 嵌套 rect，值不动
        self.assertIn('fillRule="evenodd"', text)
        self.assertIn('data-foo="1"', text)  # 未映射属性原样保留
        self.assertIn('fill="currentColor"', text)  # 属性值绝不改写
        self.assertIn("{...props}", text)
        self.assertIn("import { XizhiLucideHouse }", outv)  # 回传 import 语句

    def test_pure_function_idempotent(self):
        _, out1, _, _ = _run_sync("react")
        _, out2, _, _ = _run_sync("react")
        self.assertEqual((out1 / "XizhiLucideHouse.tsx").read_bytes(),
                         (out2 / "XizhiLucideHouse.tsx").read_bytes())

    def test_batch_names_generate_components(self):
        rc, out_dir, outv, errv = _run_sync("react", name="house, bell")
        self.assertEqual(rc, 0)
        self.assertTrue((out_dir / "XizhiLucideHouse.tsx").is_file())
        self.assertTrue((out_dir / "XizhiLucideBell.tsx").is_file())
        self.assertIn("2 wrote", outv)


